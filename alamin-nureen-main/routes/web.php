// Files generated by legacy-compatible services are written under app/Legacy
// because the original V4 filesystem logic uses __DIR__. Public static files
// are served directly first; these routes serve newly generated files.
Route::get('/uploads/{path}', function (string $path) {
    $safe = str_replace(['..', '\\'], '', $path);
    $file = app_path('Legacy/uploads/'.$safe);
    abort_unless(is_file($file), 404);
    return response()->file($file);
})->where('path', '.*');

Route::get('/generated/{path}', function (string $path) {
    $safe = str_replace(['..', '\\'], '', $path);
    $file = app_path('Legacy/generated/'.$safe);
    abort_unless(is_file($file), 404);
    return response()->file($file);
})->where('path', '.*');

